def compound_phrase(match: re.Match[str]) -> str:
  # '5 кг/м³' -> пять килограммов на кубический метр, '10 м/с' -> десять метров в секунду.
  number, top, bottom = match.groups()
  forms, feminine = UNITS[top]
  tail = PER.get(bottom) or f'в {UNITS[bottom][0][0]}'

  return f'{counted(number, forms, feminine)} {tail}'


# Предлог + число + единица: падеж задаёт предлог, а не число само по себе.
GENITIVE_UNIT = re.compile(
  r'(?P<prep>(?<![А-Яа-яЁё])'
  + '|'.join(sorted(GENITIVE_PREPOSITIONS, key=len, reverse=True))
  + r')(?P<space>\s+)(?P<number>' + NUMBER_BODY + r')'
  r'\s*(?P<top>' + PLAIN_UNITS + r')(?:/(?P<bottom>' + PLAIN_UNITS + r'))?'
  r'(?![A-Za-zА-Яа-яЁё0-9/])',
  re.IGNORECASE,
)


def genitive_counted(number: str, forms: tuple[str, str, str], feminine: bool) -> str:
  # «5» + кг -> «пяти килограммов», «1» + кг -> «одного килограмма».
  words = number_words(number, UNITS_F if feminine else UNITS_M)
  converted = ' '.join(GENITIVE_WORDS.get(word, word) for word in words.split(' '))
  plain = re.sub(r'[ \u00a0]', '', drop_comma_groups(number)).lstrip('-')
  fraction = bool(re.fullmatch(r'\d+[.,]\d+', plain))
  singular = fraction or (bool(re.fullmatch(r'\d*1', plain)) and not plain.endswith('11'))

  return f'{converted} {forms[1] if singular else forms[2]}'


def genitive_unit_phrase(match: re.Match[str]) -> str:
  # 'около 5 кг' -> около пяти килограммов, 'до 10 м/с' -> до десяти метров в секунду.
  number, top = match.group('number'), match.group('top')
  bottom = match.group('bottom')

  # предлог ищется без учёта регистра, а единицы — только как в UNITS: «5 гб» не «5 ГБ»
  if top not in UNITS or (bottom is not None and bottom not in UNITS):
    return match.group(0)

  forms, feminine = UNITS[top]
  lead = f"{match.group('prep')}{match.group('space')}"
  tail = '' if bottom is None else f' {PER.get(bottom) or f"в {UNITS[bottom][0][0]}"}'
  counted_text = genitive_counted(number, forms, feminine)

  return f'{lead}{counted_text}{tail}'


