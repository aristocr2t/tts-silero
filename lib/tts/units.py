# «к» после числа — это тысячи: 15к -> 15000, 1500к -> 1500000.
KILO = re.compile(
  r'(?<![A-Za-zА-Яа-яЁё0-9.,])(' + NUMBER_BODY + r')[кk]'
  r'(?![A-Za-zА-Яа-яЁё0-9])'
)


def kilo_phrase(match: re.Match[str]) -> str:
  # Множитель отдаём числом: дальше его читает обычный разбор чисел.
  plain = re.sub(r'[ \u00a0]', '', drop_comma_groups(match.group(1)))
  value = float(plain.replace(',', '.'))

  return str(int(round(value * 1000)))


def counted(
  number: str,
  forms: tuple[str, str, str],
  feminine: bool,
  allow_half: bool = True,
) -> str:
  # Число со словом: '5' + кг -> пять килограммов, '1,5' + с -> полторы секунды.
  plain = re.sub(r'[ \u00a0]', '', number)
  digits = plain.lstrip('-')
  minus = plain.startswith('-')

  if allow_half and digits in HALF_SCALE:     # 1500 руб -> полторы тысячи рублей
    body = f'{HALF_SCALE[digits]} {forms[2]}'

    return f'минус {body}' if minus else body

  if re.fullmatch(r'1[.,]5', digits):         # 1,5 с -> полторы секунды
    body = f'{"полторы" if feminine else "полтора"} {forms[1]}'

    return f'минус {body}' if minus else body

  words = number_words(number, UNITS_F if feminine else UNITS_M)

  if not INTEGER.match(number):               # дробь требует родительного падежа
    return f'{words} {forms[1]}'

  count = abs(int(digits.replace(',', '')))

  return f'{words} {plural(count, forms)}'


def unit_phrase(match: re.Match[str]) -> str:
  """'10 мс' -> десять миллисекунд, '1500 руб' -> полторы тысячи рублей.

  shortcut: «5 с половиной» читается как «пять секунд половиной»;
  убирать 'с' из UNITS или требовать знак после единицы, когда это начнёт мешать.
  """
  number, token = match.group(1), match.group(2)
  forms, feminine = UNITS[token]

  # у самого разряда (1500 тыс) полтора-тысячи не применяем: иначе теряется множитель
  return counted(number, forms, feminine, allow_half=token not in SCALE_UNITS)


