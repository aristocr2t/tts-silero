"""Символы, которые Silero проглатывает: плюс, равно, сравнения, стрелки.

Без замены «дебил» + фото читается как «дебилфото», а «Оки» = «Окей» — одним
словом. Каждый символ заменяется словом с пробелами по краям.
"""

import re

# Плюс между словами; знак у числа (+7) и «C++» не трогаем.
PLUS = re.compile(r'(?<![A-Za-zА-Яа-яЁё0-9+])\+(?=\s|[.,!?;:)\]»]|$)')
ARITHMETIC_PLUS = re.compile(r'(?<=\d)\+(?=\d)')

# Равенство: иначе «=» исчезает и слова слипаются.
EQUALS = re.compile(r'(?<![=!<>:+-])=(?!=)')

OPERATORS = {
  '==': 'равно',
  '!=': 'не равно',
  '≠': 'не равно',
  '<=': 'меньше или равно',
  '>=': 'больше или равно',
  '→': 'следовательно',
  '->': 'следовательно',
  '&': 'и',
  '⌘': 'комманд',
  '++': 'плюс плюс',
}
OPERATOR = re.compile('|'.join(sorted(map(re.escape, OPERATORS), key=len, reverse=True)))


def operator_phrase(match: re.Match[str]) -> str:
  # Символ -> слово в пробелах, чтобы соседние слова не слиплись.
  word = OPERATORS[match.group()]

  return f' {word} '
